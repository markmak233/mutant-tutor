"""The batch's nodes: plan_batch asks the plan model for the items and checks what code can
check, apply_decision takes the owner's answer (build.py's interrupt), and collect writes
the manifest and the proposed coverage.md changes once every item has finished. Also each
item's result as the batch state keeps it, and the exercise ids a plan may not reuse.
"""

from __future__ import annotations

import json
import re
import subprocess
from datetime import date
from pathlib import Path

from pydantic import ValidationError

from tutor.graph import prompts
from tutor.graph.languages import PYTHON, Profile
from tutor.graph.nodes import Deps, describe_error, model_label
from tutor.graph.plan_selection import validate_selection
from tutor.graph.state import BatchState, ItemState, PlanItem
from tutor.materials import cache, coverage_store
from tutor.schema import Manifest, SourceRef

REPO = Path(__file__).resolve().parents[3]  # for the manifest's git commit
PLAN_RETRIES = 2  # extra plan calls when the plan breaks a rule checked here
# On a hand-calculation exercise a failing test's traceback and summary print the answer. In
# the batch folder, written by code: the validator's temp dirs never read it, and a model's
# files may not hold a pytest.ini (the safe check).
ANSWER_HIDING_INI = ("[pytest]\n# Hand-calculation batch: a traceback or summary would print "
                     "the right numbers.\naddopts = --tb=no -rN -v\n")


def item_summary(item: PlanItem, final: ItemState | None, error: str | None = None,
                 waiting: str | None = None) -> dict:
    """One item's result for the batch state (plain data, it is checkpointed). `waiting`:
    the id of the assistant request the item stopped at (assistant mode); the batch runs
    the item again once it is answered."""
    final = final or {}
    outcome = "error" if error else "waiting" if waiting else final.get("outcome", "discarded")
    summary = {"id": item.id, "lecture": item.lecture, "slides": item.slides,
               "outcome": outcome,
               "rounds": final.get("round", 0), "tokens": final.get("tokens", 0),
               "usage": final.get("usage", {"input": 0, "cached": 0, "output": 0}),
               "last_failure": error or (f"waiting for request {waiting}" if waiting
                                         else final.get("failure"))}
    if waiting:
        summary["request"] = waiting
    return summary


def latest_results(results: list[dict]) -> list[dict]:
    """Each item's last result, in first-run order: the batch state only appends, and an
    item run again after waiting for an assistant has an older "waiting" result."""
    last = {r["id"]: r for r in results}
    return [last[i] for i in dict.fromkeys(r["id"] for r in results)]


def write_manifest(deps: Deps, items: list[PlanItem], notes: str | None = None,
                   model: str | None = None) -> None:
    """List `items` (saved exercises) in the batch manifest, creating it or adding to it.
    `model`: who generated them (default: the generate model). Listing an item again
    changes nothing, so a resumed batch can run `collect` twice; the file is replaced in
    one step, so a crash leaves the old manifest or the new one, never half of one."""
    model = model or _model_names(deps)
    path = deps.batch_dir / "manifest.json"
    known = (Manifest.model_validate_json(path.read_text(encoding="utf-8"))
             if path.is_file() else None)
    if known:
        items = [i for i in items if i.id not in known.exercises]
    if not items:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    sources = list(known.sources) if known else []
    for item in items:
        # The lecture's own file, as its cache names it: L4.pdf, or notes saved as L4.html.
        read_from = cache.lecture_cache(deps.workspace, item.lecture).name.removesuffix(".md")
        source = SourceRef(path=f"lectures/{read_from}", slides=item.slides)
        if source not in sources:
            sources.append(source)
    if known:
        models = list(dict.fromkeys([*known.model.split("; "), *model.split("; ")]))
        manifest = known.model_copy(update={
            "exercises": [*known.exercises, *(i.id for i in items)], "sources": sources,
            "model": "; ".join(models)})
    else:
        manifest = Manifest(
            phase=3, date=date.today(), label=deps.batch_dir.name.split("_", 1)[-1],
            mode=deps.mode, sources=sources,
            method="generated by the phase 3 pipeline (python -m tutor.graph), checked by "
                   "python -m tutor.validation",
            model=model, git_commit=_git_commit(),
            exercises=[i.id for i in items], notes=notes or None)
    Manifest.model_validate(manifest.model_dump())  # the cross-field rules
    partial = path.with_name(path.name + ".partial")
    partial.write_text(manifest.model_dump_json(indent=2, exclude_none=True) + "\n",
                       encoding="utf-8")
    partial.replace(path)
    ini = deps.batch_dir / "pytest.ini"
    if deps.hide_answers and not ini.exists():  # an owner's own file stays
        ini.write_text(ANSWER_HIDING_INI, encoding="utf-8")


# --- the batch: plan, owner's decision, collect -----------------------------------------

def plan_batch(state: BatchState, deps: Deps) -> BatchState:
    """Ask the plan model for `count` items; check what code can check, and ask again
    (at most PLAN_RETRIES times) with the problems found."""
    lectures, count = state["lectures"], state.get("count")
    max_count = state.get("max_count", 6)
    inputs = dict(
        lectures=lectures,
        # The coverage table: rendered from coverage.json when the course has one (the
        # same bytes for the same data), else coverage.md as written, else "(none)".
        coverage=coverage_store.planner_text(deps.workspace),
        pages="\n".join(page_titles(deps.workspace, lecture) for lecture in lectures),
        existing=existing_exercises(deps.workspace), preferences=state.get("preferences", ""),
        count=count, max_count=max_count, feedback=state.get("feedback", ""),
        previous=json.dumps(state["plan"], indent=1) if state.get("plan") else "",
        mode=deps.mode, language=deps.language)
    config = deps.plan_config or deps.config
    problems: list[str] = []
    plan: list[dict] = []
    for _ in range(1 + PLAN_RETRIES):
        messages = [{"role": "system", "content": prompts.plan_spec(deps.language)},
                    {"role": "user", "content": prompts.plan_prompt(**inputs, problems=problems)}]
        reply = deps.chat(config, messages, purpose="plan", log_path=deps.llm_log,
                          max_tokens=deps.max_tokens, response_schema=deps.profile.plan_schema,
                          thinking=deps.plan_thinking)
        try:
            items = deps.profile.batch_plan.model_validate_json(reply.text).items
        except ValidationError as e:
            problems = ["the reply does not fit the JSON schema: "
                        + "; ".join(describe_error(err) for err in e.errors()[:10])]
            continue
        plan = [i.model_dump() for i in items]
        problems = plan_problems(items, lectures, count, inputs["existing"], max_count)
        if not problems:
            break
        inputs["previous"] = json.dumps(plan, indent=1)
    return {"plan": plan, "plan_problems": problems, "feedback": "", "approved": False,
            "selected_ids": None, "plan_digest": None, "generation_complete": False}


def plan_problems(items: list[PlanItem], lectures: list[str], count: int | None,
                  existing: list[str], max_count: int = 6) -> list[str]:
    """`count` None: the plan chooses how many, up to max_count."""
    found = []
    if count and len(items) != count:
        found.append(f"{len(items)} items, {count} asked for")
    if not count and len(items) > max_count:
        found.append(f"{len(items)} items, at most {max_count}: merge or drop the least "
                     "important")
    return found + blocking_problems(items, lectures, existing)


def blocking_problems(items: list[PlanItem], lectures: list[str],
                      existing: list[str]) -> list[str]:
    """What no plan may have, edited by the owner or not: a repeated or taken id (two items
    would share a drafts folder, and each draft clears it first), an unknown lecture, a
    slide range that is not one. The count is the owner's to change."""
    ids = [i.id for i in items]
    found = [f"id {i!r} is used twice" for i in sorted({i for i in ids if ids.count(i) > 1})]
    found += [f"id {i!r} already exists in another batch" for i in ids if i in existing]
    found += [f"{i.id}: lecture {i.lecture!r} is not one of {lectures}"
              for i in items if i.lecture not in lectures]
    found += [f"{i.id}: slides {i.slides!r} is not a range of slide footers like 4.15-4.24"
              for i in items if not re.fullmatch(r"\d+(\.\d+)*(-\d+(\.\d+)*)?", i.slides)]
    return found


def apply_decision(state: BatchState, decision: dict, existing: list[str],
                   profile: Profile = PYTHON) -> BatchState:
    """The owner's answer to the plan: approve (with the plan as they may have edited it)
    or send it back with feedback. The CLI refuses a plan with blocking problems first;
    this check is for any other caller."""
    if decision.get("action") == "approve":
        plan = decision.get("plan", state["plan"])
        # Retain every proposed row; only the selected subset is eligible for dispatch.
        selected = validate_selection(plan, decision.get("selected_ids"),
                                      state["lectures"], existing, profile)
        return {"plan": plan, "approved": True, "selected_ids": selected,
                "plan_digest": decision.get("plan_digest"), "generation_complete": False}
    return {"feedback": decision.get("feedback", ""), "approved": False,
            "selected_ids": None, "plan_digest": None, "generation_complete": False}


def collect(state: BatchState, deps: Deps) -> BatchState:
    """After all items: the manifest, and the coverage.md changes proposed to the owner."""
    saved = [deps.profile.plan_item.model_validate(p) for p in state["plan"]
             if any(r["id"] == p["id"] and r["outcome"] == "saved" for r in state["results"])]
    write_manifest(deps, saved, notes=("Owner's preferences: " + state["preferences"])
                   if state.get("preferences") else None,
                   model=_models_of(deps, {i.id for i in saved}))
    if saved:
        label = deps.batch_dir.name.split("_", 1)[-1]
        # With coverage.json (2026-11-10): an exercise whose lecture and slides match one
        # point exactly is marked on it (the owner sees it on the Coverage page and in the
        # rendered coverage.md); the rest, and every exercise of a course without the data,
        # is proposed in coverage-proposal.md as before, for the owner's hand.
        store = coverage_store.load(deps.workspace)
        marked, proposed = [], []
        for i in saved:
            if store is not None and coverage_store.mark_covered(
                    store, i.lecture, i.slides, f"ex:{i.id}", label):
                marked.append(i)
            else:
                proposed.append(i)
        if marked:
            coverage_store.save(deps.workspace, store)
        lines = ["# Proposed coverage changes", "",
                 "Generated exercises; mark their knowledge points once the owner has looked "
                 "at them (not applied automatically).", ""]
        lines += [f"- {i.lecture}, slides {i.slides} ({i.knowledge_point}): gap-code -> "
                  f"ex:{i.id} ({label})" for i in proposed]
        if marked:
            lines += ["", "Marked in coverage.json already (the lecture and slides matched "
                      "one point):"] + [f"- {i.lecture}, slides {i.slides}: ex:{i.id}"
                                        for i in marked]
        (deps.batch_dir / "coverage-proposal.md").write_text("\n".join(lines) + "\n",
                                                             encoding="utf-8")
    # A manifest is absent when every selected item failed; completion is still durable.
    return {"generation_complete": True}


def _models_of(deps: Deps, ids: set[str]) -> str | None:
    """The models that generated the saved `ids`, from the batch log: a batch resumed with
    another --profile mixes models, and the manifest names them all."""
    if not deps.generation_log.is_file():
        return None
    lines = [json.loads(line)
             for line in deps.generation_log.read_text(encoding="utf-8").splitlines()]
    saved = [x for x in lines if x["exercise"] in ids and x["outcome"] == "saved"]
    models = ([x["model"] for x in saved]
              + [f"repair {x['repair_model']}" for x in saved if x.get("repair_model")]
              + [f"oracle {x['oracle_model']}" for x in saved if x.get("oracle_model")])
    return "; ".join(dict.fromkeys(models)) or None


def _model_names(deps: Deps) -> str:
    """e.g. "deepseek: deepseek-v4-flash; oracle gpt-terra: gpt-6.1-terra"."""
    names = model_label(deps.config)
    if deps.oracle_config:
        names += f"; oracle {model_label(deps.oracle_config)}"
    return names


def page_titles(workspace: Path, lecture: str) -> str:
    """One line per cached page: PDF page, slide footer and its first line of text."""
    path = cache.lecture_cache(workspace, lecture)
    lines = [f"{lecture}:"]
    for e in sorted(cache.load(path).values(), key=lambda e: e.number):
        title = next((t for t in (line.strip().strip("#").strip() for line in e.body.splitlines())
                      if t and t != e.label and not re.fullmatch(r"[\d.]+", t)), "")
        lines.append(f"  p.{e.number} · slide {e.label or '?'}: {title[:80]}")
    return "\n".join(lines)


def existing_ids(workspace: Path) -> list[str]:
    """Every exercise id in the workspace's batches; a plan may not reuse one."""
    batches = workspace / "batches"
    return sorted({p.name for p in batches.glob("*/exercises/*")
                   if p.is_dir() and not p.name.startswith((".", "_"))})


def existing_exercises(workspace: Path) -> list[str]:
    """One line per existing exercise, "id: title [topic]", for the plan model: with ids
    alone it planned a fourth word count, since it could not see what each one does."""
    lines = []
    for exercise_id in existing_ids(workspace):
        meta = next((workspace / "batches").glob(f"*/solutions/{exercise_id}/metadata.json"), None)
        try:
            data = json.loads(meta.read_text(encoding="utf-8")) if meta else {}
        except (OSError, ValueError):  # a hand-edited or half-written file: the id still counts
            data = {}
        title = f": {data['title']}" if data.get("title") else ""
        topic = f" [{data['topic']}]" if data.get("topic") else ""
        lines.append(exercise_id + title + topic)
    return lines


def _git_commit() -> str:
    """The repository's short commit, recorded in the manifest; "unknown" outside git."""
    try:
        return subprocess.run(["git", "-C", str(REPO), "rev-parse", "--short", "HEAD"],
                              capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"
